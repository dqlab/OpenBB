@pytest.mark.parametrize("bad", ["missing", "failed", "identity", "manifest", "references", "counts", "batch-size"])
def test_approve_refuses_invalid_verification(verified_packet, tmp_path, bad):
    """No successful import can substitute for a matching PASS reference receipt."""
    root = verified_packet
    admission = admission_from(root)
    receipt = load_json(root / "verify-run/receipt.json")
    if bad == "failed":
        receipt["status"] = "FAIL"
    elif bad == "identity":
        receipt["content_identity"]["tables"]["literal_version"]["rows"] += 1
    elif bad == "manifest":
        receipt["snapshot_id"] = "0" * 64
    elif bad == "references":
        receipt["reference_verification"]["status"] = "failed"
    elif bad == "counts":
        receipt["verified"]["clean_unadjusted"] += 1
    elif bad == "batch-size":
        receipt["approved_batch_size"] += 1
    path = tmp_path / "verification.json"
    if bad != "missing":
        write_json(path, receipt)
    target = Path(admission.target)
    before = fingerprint(target), sha256(target)
    with pytest.raises(AdmissionError, match="evidence|PASS|counts"):
        approve_visibility(admission, path, expected_clean_rows=2, expected_quarantine=3,
                           expected_batches=1, output=tmp_path / "approval.json")
    assert (fingerprint(target), sha256(target)) == before
    assert read(target, basis="unadjusted") == []


