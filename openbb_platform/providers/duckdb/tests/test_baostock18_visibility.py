def test_deferred_verify_approve_asof_and_exact_replay(tmp_path, monkeypatch):
    """A real read-only verify, atomic approval, as-of boundary, and same-command replay."""
    config = packet(tmp_path)
    Driver(config).run()
    target = Path(config["target"])
    before = fingerprint(target), sha256(target)
    real_connect = duckdb.connect

    def readonly(*args, **kwargs):
        assert kwargs.get("read_only") is True
        return real_connect(*args, **kwargs)

    # The CLI children execute the same read-only production-backup/verify gates.
    with monkeypatch.context() as patch:
        patch.setattr(duckdb, "connect", readonly)
        verified = verify_deferred(config, tmp_path / "import-run/receipt.json", tmp_path / "verify-run")
    assert verified["status"] == "PASS" and (fingerprint(target), sha256(target)) == before
    admission = admission_from(tmp_path)
    with pytest.raises(AdmissionError, match="visibility-approve"):
        set_visible(target, admission.approved_manifest_hash, basis="unadjusted",
                    expected_clean_rows=2, production=admission)
    output = tmp_path / "approval.json"
    event = approve_visibility(admission, tmp_path / "verify-run/receipt.json", expected_clean_rows=2,
                               expected_quarantine=3, expected_batches=1, output=output)
    at = datetime.fromisoformat(event["known_at"])
    assert read(target, basis="unadjusted", as_of=at - timedelta(microseconds=1)) == []
    assert len(read(target, basis="unadjusted", as_of=at)) == len(read(target, basis="unadjusted")) == 2
    before = fingerprint(target), sha256(target), sha256(output)
    with monkeypatch.context() as patch:
        patch.setattr(duckdb, "connect", readonly)
        replay = approve_visibility(admission, tmp_path / "verify-run/receipt.json", expected_clean_rows=2,
                                    expected_quarantine=3, expected_batches=1, output=output)
    assert not replay["changed"] and replay["event_id"] == event["event_id"]
    assert (fingerprint(target), sha256(target), sha256(output)) == before
    assert query(target, f"SELECT count(*) FROM {SCHEMA}.visibility_event") == [(1,)]
    # Unrelated writes and normal CHECKPOINT must preserve idempotent replay.
    with duckdb.connect(str(target)) as c:
        c.execute("UPDATE a_share.attempt SET sentinel=43")
    with duckdb.connect(str(target)) as c:
        c.execute("CHECKPOINT")
    replay = approve_visibility(admission, tmp_path / "verify-run/receipt.json", expected_clean_rows=2,
                                expected_quarantine=3, expected_batches=1, output=output)
    assert replay["changed"] is False


def test_approve_transaction_rolls_back_all_visibility_state(verified_packet, tmp_path):
    """An interruption after all three inserts commits no pointer/admission/event."""
    admission = admission_from(verified_packet)

    def fail(c):
        assert c.execute(f"SELECT count(*) FROM {SCHEMA}.dataset_pointer").fetchone()[0] == 1
        raise KeyboardInterrupt("visibility interrupted")

    with pytest.raises(KeyboardInterrupt):
        approve_visibility(admission, verified_packet / "verify-run/receipt.json", expected_clean_rows=2,
                           expected_quarantine=3, expected_batches=1, output=tmp_path / "approval.json", fault_hook=fail)
    for table in ("basis_admission", "visibility_event", "dataset_pointer"):
        assert query(admission.target, f"SELECT count(*) FROM {SCHEMA}.{table}") == [(0,)]
    assert not (tmp_path / "approval.json").exists()


def test_deferred_import_interrupt_rolls_back_then_resumes(tmp_path):
    """The new mode retains per-batch rollback and never publishes during resume."""
    manifest = make_candidate(tmp_path / "candidate.duckdb", rows=50_001, quarantined=3)
    target = make_catalog(tmp_path / "catalog")
    admission = replace(authorize(tmp_path, target, manifest, "first"), visibility="deferred")

    def interrupt(c, number):
        if number == 2:
            raise KeyboardInterrupt("import interrupted")

    with pytest.raises(KeyboardInterrupt):
        import_candidate(manifest, target, production=admission, fault_hook=interrupt)
    assert query(target, f"SELECT count(*) FROM {SCHEMA}.literal_version") == [(50_000,)]
    assert query(target, f"SELECT count(*) FROM {SCHEMA}.batch_receipt") == [(1,)]
    assert query(target, f"SELECT state FROM {SCHEMA}.snapshot") == [("staging",)]
    assert read(target, basis="unadjusted") == []
    admission = replace(authorize(tmp_path, target, manifest, "resume"), visibility="deferred")
    imported = import_candidate(manifest, target, production=admission)
    assert imported["new_batches"] == 1 and imported["rows"] == 50_004 and imported["batches"] == 2
    assert read(target, basis="unadjusted") == []


def test_approve_after_restart_checkpoint_and_unrelated_writes(tmp_path):
    """Native connection restarts, layout changes and foreign counts do not bind approval."""
    config = packet(tmp_path)
    Driver(config).run()
    verify_deferred(config, tmp_path / "import-run/receipt.json", tmp_path / "verify-run")
    target = Path(config["target"])
    before = fingerprint(target)
    with duckdb.connect(str(target)) as c:
        c.execute("INSERT INTO a_share.attempt VALUES (999)")
        c.execute("CREATE TABLE unrelated_production AS SELECT 123 AS value")
        c.execute("CHECKPOINT")
    assert fingerprint(target) != before
    command = load_json(tmp_path / "verify-run/approve-command.json")["argv"]
    process = subprocess.run(command, capture_output=True, text=True, check=False)  # noqa: S603
    assert process.returncode == 0, process.stderr
    assert len(read(target, basis="unadjusted")) == 2


