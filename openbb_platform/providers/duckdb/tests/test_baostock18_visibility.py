@pytest.mark.parametrize("visibility", [None, "immediate", "deferred"])
def test_driver_visibility_default_and_explicit_modes(tmp_path, visibility):
    """Omitting the new field still completes the existing immediate chain."""
    config = packet(tmp_path, visibility)
    result = Driver(config).run()
    target = Path(config["target"])
    deferred = visibility == "deferred"
    assert result["status"] == (DEFERRED if deferred else "passed")
    assert query(target, f"SELECT count(*) FROM {SCHEMA}.dataset_pointer") == [(int(not deferred),)]
    assert len(read(target, basis="unadjusted")) == (0 if deferred else 2)
    if deferred:
        assert result["catalog_fingerprint"] == fingerprint(target)
        assert not (tmp_path / "import-run/after-import-backup").exists()
        assert all("production-visible" not in r["argv"] and "production-verify" not in r["argv"]
                   for r in result["commands"])
        assert result["next_commands"]["verify"]
    else:
        assert result["replay"]["new_batches"] == 0


